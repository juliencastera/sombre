/**
 * Create the Ed25519 key pair that signs the shared fix list.
 *
 *   node scripts/fixes-keygen.ts [private-key-path]
 *
 * The private key (default ~/.sombre/fixes-ed25519.pem) must stay out of the
 * repository: whoever holds it can push fixes to every user. The public key is
 * written to src/shared/fixes-key.ts and ships in the extension.
 */
import { generateKeyPairSync } from 'node:crypto';
import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const privatePath = process.argv[2] ?? path.join(homedir(), '.sombre', 'fixes-ed25519.pem');

if (existsSync(privatePath)) {
  console.error(`Refusing to overwrite ${privatePath}. Rotating keys invalidates every signed list in the wild.`);
  process.exit(1);
}

const { publicKey, privateKey } = generateKeyPairSync('ed25519');
mkdirSync(path.dirname(privatePath), { recursive: true });
writeFileSync(privatePath, privateKey.export({ type: 'pkcs8', format: 'pem' }), { mode: 0o600 });

// SPKI DER for Ed25519 is a fixed 12-byte header followed by the 32-byte raw key.
const raw = publicKey.export({ type: 'spki', format: 'der' }).subarray(-32).toString('base64');
writeFileSync(
  path.join(ROOT, 'src/shared/fixes-key.ts'),
  `/** Ed25519 public key (raw, base64) verifying the shared fix list. Generated by scripts/fixes-keygen.ts. */\nexport const FIXES_PUBLIC_KEY = '${raw}';\n`,
);
console.log(`Private key: ${privatePath} (keep it out of the repository)`);
console.log(`Public key:  ${raw} (written to src/shared/fixes-key.ts)`);
